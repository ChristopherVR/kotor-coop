"""Generate src/KotorCoop.Plugin/HostileSpawnTriggers.cs: the story-trigger OnEnter scripts that
spawn hostile creatures.

  python tools/hostile_spawn_triggers.py            writes the C# file
  python tools/hostile_spawn_triggers.py --check    exits 1 if the file is out of date

A script qualifies when it is placed on a trigger in some module's GIT, matches the trigger relay's
default pattern (k_p*_*), calls CreateObject, and names at least one creature template whose
FactionID is Hostile_1 or Hostile_2. For those scripts the joiner does not run the OnEnter itself
during a session and the host runs it as its own player, so the enemies exist once, in the host's
world (docs/research/trigger-relay.md, "Hostile spawn triggers"). Read-only on the game files.
"""
from __future__ import annotations

import fnmatch
import os
import re
import sys

import kotor_lore
import kotorfiles
import ncsdis

UTC_TYPE = 2027
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "KotorCoop.Plugin", "HostileSpawnTriggers.cs")


def faction(game, by_name, template):
    resource = by_name.get(template.lower() + ".utc")
    try:
        if resource is not None:
            data = resource.read()
        else:
            bif, index = game.key.entries[(template.lower(), UTC_TYPE)]
            data = game.key.bif(bif).by_index[index].read()
        return kotorfiles.GFF(data, template).root.get("FactionID")
    except Exception:
        return None


def scan():
    game = kotor_lore._g()
    names = ncsdis.routine_names(game)
    modules = sorted({f[:-4].lower() for f in os.listdir(os.path.join(game.dir, "modules"))
                      if f.lower().endswith(".rim") and not f.lower().endswith("_s.rim")})
    found = {}
    for module in modules:
        resources = [r for archive in game.module(module) for r in archive]
        by_name = {r.name.lower(): r for r in resources}
        git = next((r for r in resources if r.ext == "git"), None)
        if git is None:
            continue
        for placed in kotorfiles.GFF(git.read(), git.name).root.get("TriggerList") or []:
            template = by_name.get((placed.get("TemplateResRef") or "").lower() + ".utt")
            if template is None:
                continue
            script = (kotorfiles.GFF(template.read(), template.name).root.get("ScriptOnEnter") or "").lower()
            if not fnmatch.fnmatch(script, "k_p*_*") or script in found:
                continue
            try:
                _, code = ncsdis.load(module, script)
            except Exception:
                continue
            listing = ncsdis.disassemble(code, names)
            if not any("CreateObject(" in line for line in listing):
                continue
            strings = {m.group(1) for line in listing if (m := re.search(r"CONST\s+'(.+)'", line))}
            hostile = sorted(s for s in strings if faction(game, by_name, s) in (1, 3))
            if hostile:
                found[script] = (module, hostile)
    return found


def render(found):
    rows = "\n".join(f'        "{script}", // {module}: {", ".join(templates)}'
                     for script, (module, templates) in sorted(found.items()))
    return f'''// <auto-generated> by tools/hostile_spawn_triggers.py from the game files; do not edit by hand.
namespace KotorCoop.Plugin;

/// <summary>
/// Story-trigger OnEnter scripts that spawn hostile creatures. During a session the joiner does not
/// run these itself, and the host runs them as its own player, so the enemies exist once, in the
/// host's world, and reach the joiner as stand-ins (docs/research/trigger-relay.md, "Hostile spawn
/// triggers"). A script outside this list (a mod's own trigger) keeps the ordinary relay.
/// </summary>
internal static class HostileSpawnTriggers
{{
    private static readonly string[] Scripts =
    [
{rows}
    ];

    private static readonly byte[][] Bytes = System.Array.ConvertAll(Scripts, System.Text.Encoding.ASCII.GetBytes);

    public static int Count => Scripts.Length;

    /// <summary>True when <paramref name="resref"/> (bytes up to the first NUL, any case) is in the
    /// list. No allocation: called from inside the engine's trigger event handler.</summary>
    public static bool Contains(System.ReadOnlySpan<byte> resref)
    {{
        int length = resref.IndexOf((byte)0);
        if (length < 0)
        {{
            length = resref.Length;
        }}

        System.ReadOnlySpan<byte> name = resref[..length];
        foreach (byte[] candidate in Bytes)
        {{
            if (candidate.Length != name.Length)
            {{
                continue;
            }}

            bool same = true;
            for (int i = 0; i < name.Length && same; i++)
            {{
                byte c = name[i];
                same = (c is >= (byte)'A' and <= (byte)'Z' ? (byte)(c + 32) : c) == candidate[i];
            }}

            if (same)
            {{
                return true;
            }}
        }}

        return false;
    }}

    /// <summary><see cref="Contains(System.ReadOnlySpan{{byte}})"/> for an engine CExoString
    /// (char* data, int length; the length may count the NUL). No allocation.</summary>
    public static unsafe bool ContainsExoString(nint exoString)
    {{
        if (exoString == 0)
        {{
            return false;
        }}

        byte* data = *(byte**)exoString;
        int length = *(int*)(exoString + sizeof(nint));
        return data != null && length is > 0 and <= 32 && Contains(new System.ReadOnlySpan<byte>(data, length));
    }}

    public static bool Contains(string script) =>
        System.Array.IndexOf(Scripts, script.ToLowerInvariant()) >= 0;
}}
'''


def main(argv):
    text = render(scan())
    if "--check" in argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current.replace("\r\n", "\n") != text:
            print("HostileSpawnTriggers.cs is out of date; run python tools/hostile_spawn_triggers.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(OUT)} ({text.count(chr(10) + '        \"')} scripts)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
