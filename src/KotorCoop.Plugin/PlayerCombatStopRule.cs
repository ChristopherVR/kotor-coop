namespace KotorCoop.Plugin;

/// <summary>Binary contract for the real CancelCombat routine, including its ret4
/// argument and the active-round target clear. Queue clearing alone does not stop a round.</summary>
internal static class PlayerCombatStopRule
{
    internal static ReadOnlySpan<byte> CancelCombatBytes =>
    [
        0x56, 0x6A, 0x01, 0x8B, 0xF1, 0xE8, 0xD6, 0xF2, 0xFC, 0xFF, 0x6A, 0x01, 0x6A, 0x00, 0x8B, 0xCE,
        0xE8, 0x5B, 0x4B, 0xFF, 0xFF, 0x6A, 0x01, 0x68, 0x00, 0x00, 0x00, 0x7F, 0x8B, 0xCE, 0xE8, 0xFD,
        0xE5, 0xFC, 0xFF, 0x6A, 0x00, 0x8B, 0xCE, 0xE8, 0x04, 0x87, 0xFF, 0xFF, 0x8B, 0x44, 0x24, 0x08,
        0x8B, 0x8E, 0xC8, 0x09, 0x00, 0x00, 0x50, 0xE8, 0x44, 0x6B, 0xFD, 0xFF, 0x8B, 0x8E, 0xC8, 0x09,
        0x00, 0x00, 0xC7, 0x81, 0xCC, 0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x7F, 0x8B, 0xCE, 0xE8, 0xBD,
        0xE7, 0xFC, 0xFF, 0x85, 0xC0, 0x74, 0x22, 0x8B, 0xCE, 0xE8, 0xB2, 0xE7, 0xFC, 0xFF, 0x8B, 0x10,
        0x8B, 0xC8, 0xFF, 0x52, 0x2C, 0x85, 0xC0, 0x74, 0x10, 0x5E, 0xC7, 0x44, 0x24, 0x04, 0x00, 0x00,
        0x00, 0x00, 0x8B, 0xC8, 0xE9, 0xF7, 0x2E, 0x11, 0x00, 0x5E, 0xC2, 0x04, 0x00,
    ];

    internal static bool CodeMatches(ReadOnlySpan<byte> actual) => actual.SequenceEqual(CancelCombatBytes);

    internal static bool OwnCurrentBody(nint body, nint current, nint localPlayer,
        uint vtable, uint actualId, uint requestedId) => body != 0 && body == current && body == localPlayer
        && vtable == 0x7470C8 && requestedId != 0 && requestedId != 0x7F000000
        && (actualId & 0x7FFFFFFF) == (requestedId & 0x7FFFFFFF);

    internal static bool ActiveTargetCleared(uint target) => target == 0x7F000000;
}
